export const FONT_W = 3
export const FONT_H = 5

export function textWidth(s: string): number {
  return s.length * (FONT_W + 1) - 1
}

/** Draw text at (x,y) in palette index `color`. Unknown chars render as '?'. */
export function drawText(fb: Framebuffer, x: number, y: number, s: string, color: number): void {
  let cx = x | 0
  for (const ch of s.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS['?']
    for (let gy = 0; gy < FONT_H; gy++) {
      const row = g[gy]
      for (let gx = 0; gx < FONT_W; gx++) if (row[gx] === '#') fb.px(cx + gx, (y | 0) + gy, color)
    }
    cx += FONT_W + 1
  }
}

/** Render text into a sprite (for placing on world surfaces). */
export function textSprite(s: string, color: number, bg = 0): Sprite {
  const w = textWidth(s)
  const d = new Uint8Array(w * FONT_H)
  if (bg) d.fill(bg)
  let cx = 0
  for (const ch of s.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS['?']
    for (let gy = 0; gy < FONT_H; gy++)
      for (let gx = 0; gx < FONT_W; gx++) if (g[gy][gx] === '#') d[gy * w + cx + gx] = color
    cx += FONT_W + 1
  }
  return { w, h: FONT_H, d }
}
